// Writes docs/en/03-supported-brands.md and docs/it/03-marche-supportate.md from the app database.
// Usage: node tools/gen-brand-docs.cjs
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const d = JSON.parse(fs.readFileSync(path.join(root, 'app/src/main/assets/tvdb.json'), 'utf8'));
const rows = d.brands.map((b) => {
  const has = (k) => b.r.some((r) => r.b[k]);
  return [b.n, b.r.length, b.r.filter((r) => r.b.POWER).length, has('YOUTUBE'), has('NETFLIX')];
});
const tot = rows.reduce((s, r) => s + r[1], 0);
const table = (head, yes) => head + '\n|---|---:|---:|:-:|:-:|\n' + rows.map((r) => `| ${r[0]} | ${r[1]} | ${r[2]} | ${r[3] ? yes : ''} | ${r[4] ? yes : ''} |`).join('\n');

fs.writeFileSync(path.join(root, 'docs/en/03-supported-brands.md'), `# 3. Supported brands

[Documentation index](../README.md) · **English** · [Italiano](../it/03-marche-supportate.md)

The app contains **${rows.length} brands** and **${tot} remotes**, generated from the public
[Flipper-IRDB](https://github.com/Lucaslhm/Flipper-IRDB) database (CC0). Identical remotes are
merged, and the most complete remote of each brand comes first.

- **Remotes**: how many different remotes the app has for that brand (the numbered chips under the brand).
- **With power**: how many of them include a power code, used by the automatic search.
- **YouTube / Netflix**: at least one remote of the brand has that shortcut key.

If your brand is missing, use **"Non so la marca: prova tutte le TV"** (try every TV): many TVs
sold under small brands use the same codes as a big manufacturer.

${table('| Brand | Remotes | With power | YouTube | Netflix |', 'yes')}

Generated by \`tools/gen-brand-docs.cjs\` from \`app/src/main/assets/tvdb.json\`.
To rebuild the database see [Build from source](05-build-from-source.md#regenerate-the-database).
`);

fs.writeFileSync(path.join(root, 'docs/it/03-marche-supportate.md'), `# 3. Marche supportate

[Indice della documentazione](../README.md) · [English](../en/03-supported-brands.md) · **Italiano**

L'app contiene **${rows.length} marche** e **${tot} telecomandi**, generati dal database pubblico
[Flipper-IRDB](https://github.com/Lucaslhm/Flipper-IRDB) (CC0). I telecomandi identici sono uniti
e per ogni marca il più completo viene per primo.

- **Telecomandi**: quanti telecomandi diversi ha l'app per quella marca (i chip numerati sotto la marca).
- **Con accensione**: quanti hanno il codice di accensione, usato dalla ricerca automatica.
- **YouTube / Netflix**: almeno un telecomando della marca ha quel tasto.

Se la tua marca manca, usa **"Non so la marca: prova tutte le TV"**: molte TV di marchi piccoli
usano gli stessi codici di un grande produttore.

${table('| Marca | Telecomandi | Con accensione | YouTube | Netflix |', 'sì')}

Generato da \`tools/gen-brand-docs.cjs\` a partire da \`app/src/main/assets/tvdb.json\`.
Per ricostruire il database vedi [Compilare dai sorgenti](05-compilare.md#rigenerare-il-database).
`);
console.log('brands', rows.length, 'remotes', tot);
